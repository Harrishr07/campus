"""M07-03 Timetable: the weekly grid of a term for the sections of a company (optionally one department).

Grid rows are generated by a Timetable Generation Run or edited by hand; every save is checked against the hard
constraints in `campus.faculty.timetable.rules`, so a manual edit can never introduce a clash. Publishing turns the
grid into education Course Schedules (`campus.faculty.timetable.publish`)."""

import frappe
from frappe import _
from frappe.model.document import Document

from campus.faculty.timetable import context, rules

SHOWN = 12


class Timetable(Document):
	def validate(self):
		self.check_template()
		context.complete_entries(self)
		self.check_hard_constraints()
		self.mark_changed_since_publish()
		if not self.flags.from_generation:
			self.warn_soft_issues()

	def mark_changed_since_publish(self):
		"""A published grid or unavailability list that is edited or regenerated no longer matches its Course Schedules."""
		before = self.get_doc_before_save()
		if self.status == "Published" and before and self.content() != before.content():
			self.status = "Changed since publish"

	def content(self):
		grid = sorted(
			(e.offering, e.kind, e.faculty, e.room, e.day, int(e.period or 0)) for e in self.entries
		)
		return grid, sorted((u.faculty, u.day, int(u.period or 0)) for u in self.unavailability)

	def check_template(self):
		company = frappe.db.get_value("Timetable Slot Template", self.slot_template, "company")
		if company != self.company:
			frappe.throw(
				_("Slot Template {0} belongs to {1}, not {2}.").format(
					self.slot_template, company, self.company
				)
			)

	def violations(self):
		return rules.violations(context.entries_of(self), context.build_grid(self))

	def check_hard_constraints(self):
		found = self.violations()
		if found:
			extra = len(found) - SHOWN
			lines = [v.message for v in found[:SHOWN]] + (
				[_("... and {0} more.").format(extra)] if extra > 0 else []
			)
			frappe.throw("<br>".join(lines), title=_("Timetable Clashes"))

	def warn_soft_issues(self):
		for issue in rules.soft_issues(context.entries_of(self), context.build_grid(self)):
			frappe.msgprint(issue.message, title=_("Timetable Preference"), indicator="orange")
